"""Reproduce original Tayyn Hyzmat icons from public/brand/mark.svg geometry.
Run manually with Python 3 and Pillow; not a production build dependency.
"""
from pathlib import Path
from PIL import Image, ImageDraw, PngImagePlugin

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "android/app/src/main/res"
ORIGIN = "Original Tayyn Hyzmat vector artwork; public/brand/mark.svg; generated by scripts/generate-brand-assets.py"


def mark(size, foreground=False, round_icon=False):
    scale = 4
    image = Image.new("RGBA", (size * scale, size * scale))
    draw = ImageDraw.Draw(image)
    factor = size * scale / 80
    if not foreground:
        if round_icon:
            draw.ellipse((0, 0, size * scale - 1, size * scale - 1), fill="#111111")
        else:
            draw.rounded_rectangle((0, 0, size * scale - 1, size * scale - 1), radius=16 * factor, fill="#111111")
    # Adaptive icons use the central 66.7% safe region; the T sits well inside.
    points = [(18, 21), (62, 21), (62, 31), (45, 31), (45, 62), (35, 62), (35, 31), (18, 31)]
    if foreground:
        points = [((x - 40) * 0.82 + 40, (y - 40) * 0.82 + 40) for x, y in points]
    draw.polygon([(x * factor, y * factor) for x, y in points], fill="white")
    return image.resize((size, size), Image.Resampling.LANCZOS)


def save(image, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    metadata = PngImagePlugin.PngInfo()
    metadata.add_text("Source", ORIGIN)
    metadata.add_text("impeccable:prompt", "Source: " + ORIGIN + "; not AI raster generation.")
    metadata.add_text("Description", "Original black-and-white Tayyn Hyzmat T identity; no third-party artwork")
    image.save(path, pnginfo=metadata)


for path in (ROOT / "public/img/icons").glob("*.png"):
    with Image.open(path) as old:
        width, height = old.size
    save(mark(width), path)
for density, size in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
    directory = RES / f"mipmap-{density}"
    save(mark(size), directory / "ic_launcher.png")
    save(mark(size, round_icon=True), directory / "ic_launcher_round.png")
    save(mark(round(size * 108 / 48), foreground=True), directory / "ic_launcher_foreground.png")
save(mark(288), RES / "drawable/splash_icon.png")
for path in RES.glob("drawable*/splash.png"):
    with Image.open(path) as old:
        width, height = old.size
    image = Image.new("RGBA", (width, height), "white")
    icon_size = round(min(width, height) * 0.22)
    icon = mark(icon_size)
    image.alpha_composite(icon, ((width - icon_size) // 2, (height - icon_size) // 2))
    save(image, path)
